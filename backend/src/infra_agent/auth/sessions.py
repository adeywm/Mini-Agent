"""Persistent local accounts and revocable browser sessions.

Session bearer values are generated by the server and only their hashes are stored.
Authorization must use the user's current roles, fetched from the database on every request.
"""

from __future__ import annotations

import hashlib
import secrets
from dataclasses import dataclass
from typing import Any

import psycopg
from argon2 import PasswordHasher
from argon2.exceptions import InvalidHashError, VerifyMismatchError

_PASSWORDS = PasswordHasher()


@dataclass(frozen=True)
class Session:
    username: str
    roles: tuple[str, ...]
    csrf_token: str


def _hash_token(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


class SessionStore:
    def __init__(self, dsn: str) -> None:
        self._dsn = dsn

    def has_admin(self) -> bool:
        with psycopg.connect(self._dsn) as conn:
            row = conn.execute(
                "SELECT EXISTS(SELECT 1 FROM app_users WHERE 'admin' = ANY(roles))"
            ).fetchone()
            return bool(row and row[0])

    def bootstrap(self, username: str, password: str) -> bool:
        password_hash = _PASSWORDS.hash(password)
        with psycopg.connect(self._dsn) as conn:
            # The transaction-scoped lock serializes all first-run attempts across workers.
            conn.execute("SELECT pg_advisory_xact_lock(598104821)")
            if conn.execute("SELECT EXISTS(SELECT 1 FROM app_users)").fetchone()[0]:  # type: ignore[index]
                return False
            conn.execute(
                "INSERT INTO app_users (username, password_hash, roles) VALUES (%s,%s,%s)",
                (username, password_hash, ["admin", "operator", "auditor"]),
            )
            return True

    def login(self, username: str, password: str) -> tuple[str, Session] | None:
        with psycopg.connect(self._dsn) as conn:
            row: Any = conn.execute(
                "SELECT password_hash, roles FROM app_users WHERE username=%s", (username,)
            ).fetchone()
            if row is None:
                return None
            try:
                if not _PASSWORDS.verify(row[0], password):
                    return None
            except (VerifyMismatchError, InvalidHashError):
                return None
            token, csrf = secrets.token_urlsafe(32), secrets.token_urlsafe(32)
            conn.execute(
                "INSERT INTO app_sessions (session_hash, username, csrf_token, expires_at) "
                "VALUES (%s,%s,%s, now() + interval '8 hours')",
                (_hash_token(token), username, csrf),
            )
            return token, Session(username, tuple(row[1]), csrf)

    def get(self, token: str) -> Session | None:
        with psycopg.connect(self._dsn) as conn:
            row: Any = conn.execute(
                "SELECT u.username, u.roles, s.csrf_token FROM app_sessions s "
                "JOIN app_users u ON u.username=s.username "
                "WHERE s.session_hash=%s AND s.expires_at > now()",
                (_hash_token(token),),
            ).fetchone()
        return Session(row[0], tuple(row[1]), row[2]) if row else None

    def logout(self, token: str) -> None:
        with psycopg.connect(self._dsn) as conn:
            conn.execute("DELETE FROM app_sessions WHERE session_hash=%s", (_hash_token(token),))
