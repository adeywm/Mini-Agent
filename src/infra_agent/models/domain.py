"""Core task / plan / approval / execution contracts (docs/STATE_AND_DATA_MODELS.md).

Phase 1 only *uses* Task, Evidence and AuditEvent. The plan, policy, approval and execution
models are defined now so later phases build on fixed contracts, and so the write-disabled
broker has a typed interface to refuse.
"""

from __future__ import annotations

import hashlib
import json
import uuid
from datetime import UTC, datetime
from enum import StrEnum
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, computed_field

CANONICAL_SCHEMA_VERSION = "1.0"


def utcnow() -> datetime:
    return datetime.now(UTC)


def new_id(prefix: str) -> str:
    return f"{prefix}-{uuid.uuid4().hex[:12]}"


def canonical_json(payload: Any) -> str:
    """Stable serialization: sorted keys, no whitespace, UTF-8, no NaN."""
    return json.dumps(
        payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False
    )


def sha256_digest(payload: Any) -> str:
    return "sha256:" + hashlib.sha256(canonical_json(payload).encode("utf-8")).hexdigest()


class _Model(BaseModel):
    model_config = ConfigDict(extra="forbid")


class _Frozen(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class TaskStatus(StrEnum):
    RECEIVED = "RECEIVED"
    TRIAGING = "TRIAGING"
    INVESTIGATING = "INVESTIGATING"
    PLANNING = "PLANNING"
    POLICY_REVIEW = "POLICY_REVIEW"
    AWAITING_APPROVAL = "AWAITING_APPROVAL"
    APPROVED = "APPROVED"
    EXECUTING = "EXECUTING"
    VERIFYING = "VERIFYING"
    COMPLETED = "COMPLETED"
    PARTIALLY_COMPLETED = "PARTIALLY_COMPLETED"
    DENIED = "DENIED"
    REJECTED = "REJECTED"
    EXPIRED = "EXPIRED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"
    NEEDS_REVIEW = "NEEDS_REVIEW"


TERMINAL_STATUSES = frozenset(
    {
        TaskStatus.COMPLETED,
        TaskStatus.PARTIALLY_COMPLETED,
        TaskStatus.DENIED,
        TaskStatus.REJECTED,
        TaskStatus.EXPIRED,
        TaskStatus.FAILED,
        TaskStatus.CANCELLED,
    }
)

_S = TaskStatus
TRANSITIONS: dict[TaskStatus, frozenset[TaskStatus]] = {
    _S.RECEIVED: frozenset({_S.TRIAGING, _S.CANCELLED}),
    _S.TRIAGING: frozenset({_S.INVESTIGATING, _S.DENIED, _S.FAILED, _S.CANCELLED}),
    _S.INVESTIGATING: frozenset(
        {_S.PLANNING, _S.COMPLETED, _S.FAILED, _S.NEEDS_REVIEW, _S.CANCELLED}
    ),
    _S.PLANNING: frozenset({_S.POLICY_REVIEW, _S.FAILED, _S.CANCELLED}),
    _S.POLICY_REVIEW: frozenset({_S.AWAITING_APPROVAL, _S.APPROVED, _S.DENIED, _S.CANCELLED}),
    _S.AWAITING_APPROVAL: frozenset({_S.APPROVED, _S.REJECTED, _S.EXPIRED, _S.CANCELLED}),
    _S.APPROVED: frozenset({_S.EXECUTING, _S.POLICY_REVIEW, _S.CANCELLED}),
    _S.EXECUTING: frozenset({_S.VERIFYING, _S.FAILED, _S.PARTIALLY_COMPLETED, _S.NEEDS_REVIEW}),
    _S.VERIFYING: frozenset({_S.COMPLETED, _S.FAILED, _S.PARTIALLY_COMPLETED, _S.NEEDS_REVIEW}),
    _S.NEEDS_REVIEW: frozenset({_S.PLANNING, _S.FAILED, _S.CANCELLED}),
}


class InvalidTransition(ValueError):
    pass


class Task(_Model):
    id: str = Field(default_factory=lambda: new_id("task"))
    requester: str
    origin: Literal["cli", "api", "webhook", "event"]
    intent: str = Field(min_length=1, max_length=4000)
    account_alias: str
    region: str
    repositories: tuple[str, ...] = ()
    status: TaskStatus = TaskStatus.RECEIVED
    created_at: datetime = Field(default_factory=utcnow)
    last_updated: datetime = Field(default_factory=utcnow)
    history: list[tuple[TaskStatus, datetime]] = Field(default_factory=list)

    def transition(self, to: TaskStatus) -> None:
        allowed = TRANSITIONS.get(self.status, frozenset())
        if to not in allowed:
            raise InvalidTransition(f"{self.status} -> {to} is not allowed")
        self.history.append((self.status, self.last_updated))
        self.status = to
        self.last_updated = utcnow()


class Evidence(_Frozen):
    id: str
    source: str = Field(description="e.g. aws:ecs:DescribeServices, github:actions")
    collected_at: datetime
    summary: str
    data: dict[str, Any] = Field(default_factory=dict, description="Redacted structured payload")

    @computed_field  # type: ignore[prop-decorator]
    @property
    def digest(self) -> str:
        return sha256_digest({"source": self.source, "data": self.data})


class PlannedOperation(_Frozen):
    schema_version: Literal["1.0"] = CANONICAL_SCHEMA_VERSION
    operation_id: str
    provider: Literal["aws", "github"]
    account_alias: str
    environment: Literal["development", "staging", "production"]
    service: str
    operation: str
    region: str
    resource_scope: tuple[str, ...] = Field(min_length=1)
    parameters: dict[str, Any]
    depends_on: tuple[str, ...] = ()
    expected_outcome: str
    verification: str
    estimated_cost_change_usd_monthly: float | None = None
    idempotency_key: str = Field(description="Generated by the server, never by the model")


class ChangePlan(_Frozen):
    id: str
    version: int = Field(ge=1)
    task_id: str
    operations: tuple[PlannedOperation, ...] = Field(min_length=1)

    def canonical_payload(self) -> dict[str, Any]:
        return {
            "schema_version": CANONICAL_SCHEMA_VERSION,
            "plan_id": self.id,
            "version": self.version,
            "task_id": self.task_id,
            "operations": [op.model_dump(mode="json") for op in self.operations],
        }

    @computed_field  # type: ignore[prop-decorator]
    @property
    def digest(self) -> str:
        return sha256_digest(self.canonical_payload())


class Decision(StrEnum):
    ALLOW_AUTO = "ALLOW_AUTO"
    REQUIRE_APPROVAL = "REQUIRE_APPROVAL"
    DENY = "DENY"
    NEEDS_MORE_DATA = "NEEDS_MORE_DATA"


class PolicyDecision(_Frozen):
    plan_digest: str
    operation_id: str
    decision: Decision
    matched_rules: tuple[str, ...] = ()
    reason: str
    required_approval_level: Literal["none", "standard", "high"] = "none"


class ApprovalRequest(_Frozen):
    id: str
    plan_digest: str
    task_id: str
    scope: tuple[str, ...]
    requester: str
    approver: str | None = None
    decision: Literal["pending", "approved", "rejected", "expired"] = "pending"
    expires_at: datetime
    used_at: datetime | None = None


class ExecutionStatus(StrEnum):
    BLOCKED = "BLOCKED"
    SUCCEEDED = "SUCCEEDED"
    FAILED = "FAILED"
    AMBIGUOUS = "AMBIGUOUS"


class ExecutionRecord(_Frozen):
    id: str = Field(default_factory=lambda: new_id("exec"))
    task_id: str
    operation_id: str
    plan_digest: str
    operation_fingerprint: str
    status: ExecutionStatus
    reason: str
    attempt: int = 1
    role_alias: str | None = None
    external_request_id: str | None = None
    recorded_at: datetime = Field(default_factory=utcnow)


class AuditEvent(_Frozen):
    id: str = Field(default_factory=lambda: new_id("audit"))
    actor: str
    action: str
    target: str
    outcome: Literal["allowed", "denied", "error", "info"]
    correlation_id: str
    payload_digest: str | None = None
    detail: str = ""
    timestamp: datetime = Field(default_factory=utcnow)
